-- ============================================================================
-- Supabase PostgreSQL Production Schema for ThreatGuard AI
-- Cyber Threat & Digital Trust Intelligence Architecture
-- Includes Tables, Constraints, Indexes, Seed Data, and Row Level Security (RLS)
-- ============================================================================

-- 1. Threat Indicators (Global IOCs)
CREATE TABLE IF NOT EXISTS public.threat_indicators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator TEXT UNIQUE NOT NULL,
    indicator_type TEXT NOT NULL,
    threat_type TEXT NOT NULL,
    severity TEXT NOT NULL,
    confidence INTEGER DEFAULT 80,
    source TEXT NOT NULL,
    description TEXT,
    metadata JSONB DEFAULT '{}'::jsonb,
    first_seen TIMESTAMPTZ DEFAULT NOW(),
    last_seen TIMESTAMPTZ DEFAULT NOW(),
    is_active INTEGER DEFAULT 1
);

-- 2. Community Incident Reports (Crowdsourced Threat Telemetry)
CREATE TABLE IF NOT EXISTS public.community_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_url TEXT NOT NULL,
    domain TEXT NOT NULL,
    reporter_name TEXT DEFAULT 'Anonymous Analyst',
    reporter_role TEXT DEFAULT 'community',
    category TEXT NOT NULL,
    description TEXT NOT NULL,
    impersonated_brand TEXT,
    evidence_notes TEXT,
    upvotes INTEGER DEFAULT 1,
    downvotes INTEGER DEFAULT 0,
    status TEXT DEFAULT 'verified',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Community Votes (Consensus Validation)
CREATE TABLE IF NOT EXISTS public.community_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT REFERENCES public.community_reports(id) ON DELETE CASCADE,
    voter_ip TEXT NOT NULL,
    vote_type TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(report_id, voter_ip)
);

-- 4. Audit Scan History (Telemetry Log)
CREATE TABLE IF NOT EXISTS public.scan_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    domain TEXT NOT NULL,
    risk_score INTEGER NOT NULL,
    trust_score INTEGER NOT NULL,
    risk_level TEXT NOT NULL,
    summary TEXT,
    scan_result JSONB DEFAULT '{}'::jsonb,
    scanned_at TIMESTAMPTZ DEFAULT NOW()
);

-- Performance Indexes
CREATE INDEX IF NOT EXISTS idx_threat_indicators_domain ON public.threat_indicators(indicator);
CREATE INDEX IF NOT EXISTS idx_threat_indicators_active ON public.threat_indicators(is_active);
CREATE INDEX IF NOT EXISTS idx_community_reports_domain ON public.community_reports(domain);
CREATE INDEX IF NOT EXISTS idx_scan_history_domain ON public.scan_history(domain);

-- ============================================================================
-- Row Level Security (RLS) Configuration
-- ============================================================================
ALTER TABLE public.threat_indicators ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.community_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.community_votes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scan_history ENABLE ROW LEVEL SECURITY;

-- Threat Indicators: Anyone can read active indicators
CREATE POLICY "Public Read Threat Indicators" 
ON public.threat_indicators FOR SELECT 
USING (is_active = 1);

-- Threat Indicators: Authenticated / Anon can insert or update with service
CREATE POLICY "Public Insert Threat Indicators" 
ON public.threat_indicators FOR INSERT 
WITH CHECK (true);

-- Community Reports: Anyone can view verified community reports
CREATE POLICY "Public Read Community Reports" 
ON public.community_reports FOR SELECT 
USING (true);

-- Community Reports: Anyone can submit new threat reports
CREATE POLICY "Public Insert Community Reports" 
ON public.community_reports FOR INSERT 
WITH CHECK (true);

-- Community Reports: Upvote / Downvote updates
CREATE POLICY "Public Update Community Reports" 
ON public.community_reports FOR UPDATE 
USING (true);

-- Community Votes: Anyone can view and register a vote
CREATE POLICY "Public Read Community Votes" 
ON public.community_votes FOR SELECT 
USING (true);

CREATE POLICY "Public Insert Community Votes" 
ON public.community_votes FOR INSERT 
WITH CHECK (true);

-- Scan History: Anyone can read past scans
CREATE POLICY "Public Read Scan History" 
ON public.scan_history FOR SELECT 
USING (true);

CREATE POLICY "Public Insert Scan History" 
ON public.scan_history FOR INSERT 
WITH CHECK (true);

